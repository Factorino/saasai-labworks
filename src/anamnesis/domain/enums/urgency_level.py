from enum import IntEnum


class UrgencyLevel(IntEnum):
    """Уровень срочности обращения за помощью.

    Соответствует классам `L0`–`L3` онтологии и их представителям `L0_`–`L3_`.
    Уровни упорядочены, поэтому итоговый уровень — `max` по утверждённым.

    Attributes:
        L0: Можно попробовать самопомощь и понаблюдать.
        L1: Желательно рассмотреть консультацию специалиста.
        L2: Рекомендуется обратиться к специалисту.
        L3: Необходимо срочно обратиться за помощью.
    """

    L0 = 0
    L1 = 1
    L2 = 2
    L3 = 3
