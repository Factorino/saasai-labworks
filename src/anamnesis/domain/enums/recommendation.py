from enum import IntEnum, StrEnum, auto


class UrgencyLevel(IntEnum):
    """Уровень срочности обращения за помощью.

    Соответствует классам `L0`–`L3` онтологии и их представителям `L0_`–`L3_`.
    Уровни упорядочены, поэтому итоговый уровень — `max` по утверждённым.

    Attributes:
        L0: Можно попробовать самопомощь и понаблюдать.
        L1: Желательно рассмотреть консультацию специалиста.
        L2: Рекомендуется обратиться к специалисту.
        L3: Необходимо срочно обратиться за помощью.
    """

    L0 = 0
    L1 = 1
    L2 = 2
    L3 = 3


class Referral(StrEnum):
    """Куда обратиться за помощью помимо самопомощи.

    Соответствует ветви `Referral` онтологии. Порядок членов — порядок показа
    направлений в сводке, от самого срочного к наименее срочному; менять его нельзя.

    Attributes:
        EMERGENCY_MEDICAL_CARE: Срочная медицинская помощь.
        CRISIS_HELPLINE: Службы экстренной психологической помощи.
        DOCTOR_VISIT: Сначала обратиться к врачу.
    """

    EMERGENCY_MEDICAL_CARE = auto()
    CRISIS_HELPLINE = auto()
    DOCTOR_VISIT = auto()
